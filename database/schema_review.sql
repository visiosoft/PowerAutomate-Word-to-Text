-- =============================================================================
-- 1. DOCUMENTS
--    Stores uploaded Word documents (binary). ContentHash enables deduplication
--    so the same document isn't stored twice.
-- =============================================================================
CREATE TABLE Documents (
    DocumentID        INT IDENTITY(1,1) PRIMARY KEY,
    FileName          NVARCHAR(255)       NULL,
    FileSizeBytes     BIGINT              NULL,
    ContentHash       CHAR(64)            NOT NULL,   -- SHA-256
    OriginalContent   VARBINARY(MAX)      NULL,       -- raw .docx
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE(),

    CONSTRAINT UQ_Documents_ContentHash UNIQUE (ContentHash)
);


-- =============================================================================
-- 2. CONVERSION REQUESTS
--    Audit log for every API call. Tracks which endpoint was hit, how long
--    it took, whether it succeeded or failed, and which document was used.
-- =============================================================================
CREATE TABLE ConversionRequests (
    RequestID         INT IDENTITY(1,1) PRIMARY KEY,
    DocumentID        INT                 NULL REFERENCES Documents(DocumentID),
    Endpoint          VARCHAR(20)         NOT NULL,   -- /api/decode | /api/section | /api/html | /api/headers | /api/compare
    TitleFilter       NVARCHAR(255)       NULL,       -- optional ?title= query param
    RequestSource     VARCHAR(50)         NULL,       -- 'raw-binary' | 'json-base64'
    Status            VARCHAR(20)         NOT NULL DEFAULT 'success',  -- success | error
    ErrorMessage      NVARCHAR(MAX)       NULL,
    ResponseSizeBytes INT                 NULL,
    ProcessingTimeMs  INT                 NULL,
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE()
);


-- =============================================================================
-- 3. DOCUMENT SECTIONS
--    H1-level sections extracted from each Word document. The API splits
--    documents by H1 headings; each section becomes a row here.
-- =============================================================================
CREATE TABLE DocumentSections (
    SectionID         INT IDENTITY(1,1) PRIMARY KEY,
    DocumentID        INT                 NOT NULL REFERENCES Documents(DocumentID),
    RequestID         INT                 NULL     REFERENCES ConversionRequests(RequestID),
    SectionNumber     INT                 NOT NULL,
    Title             NVARCHAR(500)       NOT NULL,
    HtmlContent       NVARCHAR(MAX)       NULL,       -- full HTML for this section
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE()
);


-- =============================================================================
-- 4. SECTION ANCHORS
--    H2 headings inside each section, used to generate the table-of-contents
--    navigation (the black button list on the right side of the page).
-- =============================================================================
CREATE TABLE SectionAnchors (
    AnchorID          INT IDENTITY(1,1) PRIMARY KEY,
    SectionID         INT                 NOT NULL REFERENCES DocumentSections(SectionID),
    HeadingText       NVARCHAR(500)       NOT NULL,
    AnchorId          VARCHAR(200)        NOT NULL,   -- slug for #hash links
    SortOrder         INT                 NOT NULL
);


-- =============================================================================
-- 5. NAVIGATION CONFIGURATION
--    Replaces the hardcoded NAVIGATION_CONFIG object in server.js. Maps each
--    section title to its previous/next/home URLs for the navigation buttons.
-- =============================================================================
CREATE TABLE NavigationConfig (
    NavID             INT IDENTITY(1,1) PRIMARY KEY,
    SectionTitle      NVARCHAR(255)       NOT NULL,
    SectionNumber     INT                 NOT NULL,
    PreviousUrl       NVARCHAR(500)       NOT NULL,
    NextUrl           NVARCHAR(500)       NOT NULL,
    HomeUrl           NVARCHAR(500)       DEFAULT '/sites/InnovationArtsEntertainment/SitePages/HANDBOOK.aspx',
    IsActive          BIT                 DEFAULT 1,
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE(),
    UpdatedAt         DATETIME2           DEFAULT GETUTCDATE(),

    CONSTRAINT UQ_NavigationConfig_SectionTitle UNIQUE (SectionTitle)
);

