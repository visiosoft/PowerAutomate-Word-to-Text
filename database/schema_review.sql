-- =============================================================================
-- 6. PAGE TEMPLATES
--    Stores the SharePoint canvas JSON templates (currently hardcoded as
--    INTRO_TEMPLATE and SECTIONTEMPLATE in server.js). Allows updating
--    templates without redeploying the application.
-- =============================================================================
CREATE TABLE PageTemplates (
    TemplateID        INT IDENTITY(1,1) PRIMARY KEY,
    TemplateName      VARCHAR(50)         NOT NULL,   -- 'intro' | 'section'
    CanvasContent1    NVARCHAR(MAX)       NOT NULL,   -- JSON template string
    IsActive          BIT                 DEFAULT 1,
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE(),
    UpdatedAt         DATETIME2           DEFAULT GETUTCDATE(),

    CONSTRAINT UQ_PageTemplates_TemplateName UNIQUE (TemplateName)
);


-- =============================================================================
-- 7. DOCUMENT COMPARISONS
--    Results from the /api/compare endpoint. Stores the AI-generated summary
--    of differences between two versions of a document.
-- =============================================================================
CREATE TABLE DocumentComparisons (
    ComparisonID      INT IDENTITY(1,1) PRIMARY KEY,
    LastDocumentID    INT                 NOT NULL REFERENCES Documents(DocumentID),
    CurrentDocumentID INT                 NOT NULL REFERENCES Documents(DocumentID),
    RequestID         INT                 NULL     REFERENCES ConversionRequests(RequestID),
    SummaryJSON       NVARCHAR(MAX)       NULL,       -- full AI response
    LastSizeBytes     INT                 NULL,
    CurrentSizeBytes  INT                 NULL,
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE()
);


-- =============================================================================
-- 8. COMPARISON CHANGES
--    Individual change items from a comparison, each tied to a heading.
-- =============================================================================
CREATE TABLE ComparisonChanges (
    ChangeID          INT IDENTITY(1,1) PRIMARY KEY,
    ComparisonID      INT                 NOT NULL REFERENCES DocumentComparisons(ComparisonID),
    Heading           NVARCHAR(500)       NULL,
    ChangeDescription NVARCHAR(MAX)       NULL,
    SortOrder         INT                 NOT NULL
);


-- =============================================================================
-- 9. DOCUMENT IMAGES
--    Tracks {{image_url}} placeholders found in documents and their resolved
--    URLs after conversion.
-- =============================================================================
CREATE TABLE DocumentImages (
    ImageID           INT IDENTITY(1,1) PRIMARY KEY,
    DocumentID        INT                 NOT NULL REFERENCES Documents(DocumentID),
    OriginalUrl       NVARCHAR(1000)      NOT NULL,
    ResolvedUrl       NVARCHAR(1000)      NULL,
    CreatedAt         DATETIME2           DEFAULT GETUTCDATE()
);


-- =============================================================================
-- INDEXES
-- =============================================================================
CREATE INDEX IX_ConversionRequests_DocumentID  ON ConversionRequests(DocumentID);
CREATE INDEX IX_ConversionRequests_Endpoint    ON ConversionRequests(Endpoint);
CREATE INDEX IX_ConversionRequests_CreatedAt   ON ConversionRequests(CreatedAt);
CREATE INDEX IX_DocumentSections_DocumentID    ON DocumentSections(DocumentID);
CREATE INDEX IX_DocumentSections_Title         ON DocumentSections(Title);
CREATE INDEX IX_NavigationConfig_IsActive      ON NavigationConfig(IsActive);
CREATE INDEX IX_DocumentComparisons_CreatedAt  ON DocumentComparisons(CreatedAt);
CREATE INDEX IX_SectionAnchors_SectionID       ON SectionAnchors(SectionID);
CREATE INDEX IX_DocumentImages_DocumentID      ON DocumentImages(DocumentID);
